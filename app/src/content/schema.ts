import { boolean, char, datetime, index, int, json, mediumtext, mysqlTable, varchar } from 'drizzle-orm/mysql-core';
import type { ContentRules } from './contracts.ts';
export const contentBlogRules = mysqlTable(
  'content_blog_rules',
  {
    blogId: int('blog_id').primaryKey(),
    platform: varchar('platform', { length: 32 }).notNull(),
    adapterId: varchar('adapter_id', { length: 64 }).notNull(),
    adapterVersion: varchar('adapter_version', { length: 32 }).notNull(),
    rules: json('rules').$type<ContentRules>().notNull(),
    ruleSource: varchar('rule_source', { length: 16 }).notNull(),
    ruleRevision: int('rule_revision').notNull().default(1),
    lastMethod: varchar('last_method', { length: 32 }),
    lastStatus: varchar('last_status', { length: 32 }).notNull().default('pending'),
    lastError: varchar('last_error', { length: 64 }),
    lastAttemptAt: datetime('last_attempt_at'),
    lastSuccessAt: datetime('last_success_at'),
    updatedAt: datetime('updated_at').notNull(),
  },
  (t) => [index('content_rules_status').on(t.lastStatus, t.blogId)],
);
export const contentPostBodies = mysqlTable(
  'content_post_bodies',
  {
    postId: int('post_id').primaryKey(),
    blogId: int('blog_id').notNull(),
    bodyText: mediumtext('body_text'),
    bodyHtml: mediumtext('body_html'),
    contentHash: char('content_hash', { length: 64 }),
    revision: int('revision').notNull().default(1),
    completeness: varchar('completeness', { length: 16 }).notNull(),
    status: varchar('status', { length: 16 }).notNull(),
    sourceKind: varchar('source_kind', { length: 32 }).notNull(),
    sourceUrl: varchar('source_url', { length: 1024 }).notNull(),
    articleUrl: varchar('article_url', { length: 1024 }).notNull(),
    adapterId: varchar('adapter_id', { length: 64 }).notNull(),
    adapterVersion: varchar('adapter_version', { length: 32 }).notNull(),
    ruleRevision: int('rule_revision').notNull(),
    obtainedAt: datetime('obtained_at').notNull(),
    sourceUpdatedAt: datetime('source_updated_at'),
    nextAttemptAt: datetime('next_attempt_at').notNull(),
    lastAttemptAt: datetime('last_attempt_at').notNull(),
    lastError: varchar('last_error', { length: 64 }),
    etag: varchar('etag', { length: 512 }),
    lastModified: varchar('last_modified', { length: 255 }),
    imageOnly: boolean('image_only').notNull().default(false),
    truncated: boolean('truncated').notNull().default(false),
    coverage: varchar('coverage', { length: 32 }).notNull(),
    pageLinks: json('page_links'),
  },
  (t) => [
    index('content_bodies_due').on(t.nextAttemptAt, t.postId),
    index('content_bodies_blog').on(t.blogId, t.status),
    index('content_bodies_schedule').on(t.postId, t.adapterVersion, t.sourceKind, t.status),
  ],
);
export const contentAttempts = mysqlTable(
  'content_attempts',
  {
    id: char('id', { length: 64 }).primaryKey(),
    postId: int('post_id').notNull(),
    blogId: int('blog_id').notNull(),
    sourceKind: varchar('source_kind', { length: 32 }).notNull(),
    sourceUrl: varchar('source_url', { length: 1024 }).notNull(),
    adapterId: varchar('adapter_id', { length: 64 }).notNull(),
    status: varchar('status', { length: 32 }).notNull(),
    reason: varchar('reason', { length: 64 }),
    contentHash: char('content_hash', { length: 64 }),
    rawBytes: int('raw_bytes').notNull(),
    observedAt: datetime('observed_at').notNull(),
  },
  (t) => [index('content_attempts_post').on(t.postId, t.observedAt), index('content_attempts_date').on(t.observedAt)],
);
